#!/bin/bash

# ==========================================
# 1. 환경 변수 및 기본 설정
# ==========================================

# 모니터링 결과를 저장할 로그 파일 경로다.
# agent-app의 상태, CPU 사용률, 메모리 사용률, 디스크 사용률, 경고 메시지가 이 파일에 누적된다.
LOG_FILE="/var/log/agent-app/monitor.log"

# 감시할 애플리케이션 프로세스 이름이다.
# pgrep 명령어가 이 이름을 기준으로 실행 중인 프로세스를 찾는다.
APP_NAME="agent-app"

# agent-app이 사용하는 TCP 포트 번호다.
# ss 명령어를 사용하여 이 포트가 LISTEN 상태인지 확인한다.
PORT="15034"

# 현재 시간을 저장한다.
# 로그에 기록되는 시간 형식은 [YYYY-MM-DD HH:MM:SS] 형태다.
NOW=$(date +"%Y-%m-%d %H:%M:%S")

# 경고 메시지를 누적 저장할 변수다.
# CPU, 메모리, 디스크, 방화벽 상태에 문제가 있으면 이 변수에 [WARNING] 문구가 추가된다.
WARNINGS=""


# ==========================================
# 2. Health Check
# ==========================================
# Health Check는 애플리케이션이 정상 실행 중인지 먼저 확인하는 단계다.
# 이 단계에서 실패하면 모니터링 값을 기록하지 않고 즉시 종료한다.
# 이유는 앱이 실행 중이 아니면 CPU, 메모리 사용량 등을 기록해도 의미가 없기 때문이다.


# ------------------------------------------
# 2-1. 프로세스 실행 여부 확인
# ------------------------------------------

# pgrep -x "$APP_NAME"은 이름이 정확히 agent-app인 프로세스를 찾는다.
# head -n 1은 여러 개가 검색될 경우 첫 번째 PID만 사용하기 위한 명령어다.
PID=$(pgrep -x "$APP_NAME" | head -n 1)

# PID 값이 비어 있다는 것은 agent-app 프로세스가 실행 중이 아니라는 뜻이다.
# 이 경우 정상적인 서비스 상태가 아니므로 스크립트를 종료한다.
if [ -z "$PID" ]; then
    exit 1
fi


# ------------------------------------------
# 2-2. 포트 LISTEN 상태 확인
# ------------------------------------------

# ss -tln은 현재 서버에서 LISTEN 중인 TCP 포트 목록을 보여준다.
# grep -q ":$PORT "는 15034 포트가 열려 있는지 조용히 검사한다.
# -q 옵션은 결과를 화면에 출력하지 않고 성공/실패 여부만 반환한다.
if ! ss -tln | grep -q ":$PORT "; then
    exit 1
fi


# ==========================================
# 3. 보안 상태 점검
# ==========================================
# 이 단계에서는 방화벽 상태를 확인한다.
# 앱이 실행 중이더라도 방화벽이 꺼져 있으면 보안상 위험할 수 있다.
# 다만 앱 자체가 중단된 것은 아니므로 exit 하지 않고 경고만 로그에 남긴다.


# ------------------------------------------
# 3-1. UFW 활성화 상태 확인
# ------------------------------------------

# /etc/ufw/ufw.conf 파일에서 ENABLED 값만 가져온다.
# ENABLED=yes이면 UFW 방화벽이 활성화된 상태다.
UFW_STATUS=$(grep "^ENABLED=" /etc/ufw/ufw.conf | cut -d= -f2)

# UFW 상태가 yes가 아니면 방화벽이 꺼져 있거나 비정상 상태라고 판단한다.
# 이 경우 WARNINGS 변수에 경고 메시지를 추가한다.
if [ "$UFW_STATUS" != "yes" ]; then
    WARNINGS="${WARNINGS}[WARNING] Firewall Inactive "
fi


# ==========================================
# 4. 자원 사용량 수집 및 임계값 경고
# ==========================================
# 이 단계에서는 CPU, 메모리, 디스크 사용량을 수집한다.
# 각 항목이 정해진 임계값을 넘으면 WARNINGS 변수에 경고 문구를 추가한다.
# 경고가 있더라도 로그 기록은 계속 수행한다.


# ------------------------------------------
# 4-1. CPU 사용률 확인
# ------------------------------------------

# top -bn1은 top 명령어를 1회만 실행하여 현재 CPU 상태를 출력한다.
# grep "Cpu(s)"는 CPU 사용량이 포함된 줄만 추출한다.
# sed 명령어는 idle 값을 추출한다.
# idle은 CPU가 쉬고 있는 비율이다.
CPU_IDLE=$(top -bn1 | grep "Cpu(s)" | sed -E 's/.*, ([0-9.]+) id.*/\1/')

# CPU 사용률은 100 - idle 값으로 계산한다.
# awk를 사용해 소수점 첫째 자리까지 출력한다.
CPU_USAGE=$(awk -v idle="$CPU_IDLE" 'BEGIN {printf "%.1f", 100 - idle}')

# CPU 사용률 임계값은 20%다.
# CPU_USAGE가 20보다 크면 경고 메시지를 추가한다.
# bash는 소수점 비교를 직접 하기 어렵기 때문에 awk를 사용한다.
if [ $(awk -v cpu="$CPU_USAGE" 'BEGIN {if (cpu > 20) print 1; else print 0}') -eq 1 ]; then
    WARNINGS="${WARNINGS}[WARNING] CPU > 20% "
fi


# ------------------------------------------
# 4-2. 메모리 사용률 확인
# ------------------------------------------

# free 명령어는 시스템 메모리 사용량을 보여준다.
# /Mem/ 줄에서 전체 메모리($2)와 사용 중인 메모리($3)를 가져온다.
# 사용률은 사용 중인 메모리 / 전체 메모리 * 100 으로 계산한다.
MEM_USAGE=$(free | awk '/Mem/ {printf "%.1f", $3/$2 * 100}')

# 메모리 사용률 임계값은 10%다.
# MEM_USAGE가 10보다 크면 경고 메시지를 추가한다.
# 여기서도 소수점 비교를 위해 awk를 사용한다.
if [ $(awk -v mem="$MEM_USAGE" 'BEGIN {if (mem > 10) print 1; else print 0}') -eq 1 ]; then
    WARNINGS="${WARNINGS}[WARNING] MEM > 10% "
fi


# ------------------------------------------
# 4-3. 디스크 사용률 확인
# ------------------------------------------

# df / 는 루트 파티션의 디스크 사용량을 확인한다.
# NR==2는 df 출력 결과 중 두 번째 줄, 즉 실제 디스크 정보 줄을 의미한다.
# $5는 사용률 항목이다.
# sed 's/%//'는 % 기호를 제거하여 숫자만 남긴다.
DISK_USAGE=$(df / | awk 'NR==2 {print $5}' | sed 's/%//')

# 디스크 사용률 임계값은 80%다.
# 디스크 사용률이 80보다 크면 경고 메시지를 추가한다.
if [ "$DISK_USAGE" -gt 80 ]; then
    WARNINGS="${WARNINGS}[WARNING] DISK_USED > 80% "
fi


# ==========================================
# 5. 로그 기록
# ==========================================
# 수집한 상태 정보를 한 줄의 로그 메시지로 만든다.
# 로그에는 시간, PID, CPU 사용률, 메모리 사용률, 디스크 사용률, 경고 메시지가 포함된다.


# ------------------------------------------
# 5-1. 로그 메시지 생성
# ------------------------------------------

# 요구된 로그 형식은 다음과 같다.
# [YYYY-MM-DD HH:MM:SS] PID:... CPU:..% MEM:..% DISK_USED:..%
# WARNINGS 값이 비어 있으면 일반 상태 로그만 남는다.
# WARNINGS 값이 있으면 같은 줄 끝에 경고 메시지가 추가된다.
LOG_MSG="[$NOW] PID:$PID CPU:${CPU_USAGE}% MEM:${MEM_USAGE}% DISK_USED:${DISK_USAGE}% $WARNINGS"


# ------------------------------------------
# 5-2. 로그 파일에 기록
# ------------------------------------------

# sed 's/[[:space:]]*$//'는 줄 끝의 불필요한 공백을 제거한다.
# WARNINGS가 비어 있을 때 로그 끝에 공백이 남는 것을 방지하기 위한 처리다.
# >> 는 기존 로그 파일 내용을 유지하면서 맨 아래에 새 로그를 추가한다.
echo "$LOG_MSG" | sed 's/[[:space:]]*$//' >> "$LOG_FILE"


# ==========================================
# 6. 로그 파일 용량 관리
# ==========================================
# 로그 파일은 계속 누적되므로 크기 제한이 필요하다.
# 파일이 너무 커지면 디스크 공간을 차지하고 관리가 어려워진다.
# 따라서 monitor.log가 10MB 이상이면 기존 로그를 백업하고 새 로그 파일을 만든다.


# ------------------------------------------
# 6-1. 최대 로그 파일 크기 설정
# ------------------------------------------

# 10MB를 byte 단위로 표현한 값이다.
# 10 * 1024 * 1024 = 10485760
MAX_SIZE=10485760 # 10MB

# 현재 로그 파일 크기를 byte 단위로 확인한다.
# stat -c%s는 파일 크기를 byte로 출력한다.
# 로그 파일이 아직 없거나 오류가 나면 0으로 처리한다.
FILE_SIZE=$(stat -c%s "$LOG_FILE" 2>/dev/null || echo 0)


# ------------------------------------------
# 6-2. 로그 파일 순환 저장
# ------------------------------------------

# 로그 파일 크기가 10MB 이상이면 로그 로테이션을 수행한다.
if [ "$FILE_SIZE" -ge "$MAX_SIZE" ]; then

    # 기존 백업 파일을 한 단계씩 뒤로 민다.
    # monitor.log.9가 있으면 monitor.log.10이 된다.
    # monitor.log.1이 있으면 monitor.log.2가 된다.
    # 높은 번호부터 처리해야 파일이 덮어쓰기 되지 않는다.
    for i in {9..1}; do
        [ -f "${LOG_FILE}.${i}" ] && mv "${LOG_FILE}.${i}" "${LOG_FILE}.$((i+1))"
    done

    # 현재 monitor.log 파일을 monitor.log.1로 백업한다.
    mv "$LOG_FILE" "${LOG_FILE}.1"

    # 새로운 빈 monitor.log 파일을 만든다.
    touch "$LOG_FILE"

    # 새 로그 파일 권한을 660으로 설정한다.
    # 소유자와 그룹은 읽기/쓰기 가능, 기타 사용자는 접근 불가다.
    chmod 660 "$LOG_FILE"
fi